import { chromium as pw } from '@playwright/test';
import chromium from '@sparticuz/chromium';
import fs from 'node:fs';
const out = new URL('../test-results/', import.meta.url).pathname;
fs.mkdirSync(out, { recursive: true });
const args = chromium.args.filter(a => a !== '--single-process').concat(['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox']);
const browser = await pw.launch({ executablePath: await chromium.executablePath(), args, headless: true, env: { ...process.env, LD_LIBRARY_PATH: '/home/user/.local/lib/chromium-deps' } });
const page = await browser.newPage({ viewport: { width: 1100, height: 680 } });
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
await page.goto(`${process.env.BASE_URL || 'http://localhost:3000'}/play.html?test=1`, { waitUntil: 'domcontentloaded' });
await page.waitForSelector('#topbar:not(.hidden)', { timeout: 120000 });await page.click('#menu-garage');
await page.addStyleTag({ content: '*{backdrop-filter:none!important;animation:none!important;transition:none!important}' });
await page.click('.car-card[data-car="ferrari"]');
await page.waitForTimeout(800);
await page.screenshot({ path: out + 'ferrari-garage.png', timeout: 90000 });
await page.click('#btn-start');
await page.keyboard.down('ArrowUp');
await page.waitForFunction(() => window.__overtake.speed > 22, { timeout: 40000 });
await page.waitForTimeout(300);
await page.screenshot({ path: out + 'ferrari-close.png', timeout: 90000 });
const info = await page.evaluate(() => {
  const g = window.__overtake;
  const p = g.player;
  return { cam: g.getCameraSettings(), wrapperRot: p.rotation.y, innerRot: p.children[0]?.rotation?.y, mode: g.mode };
});
await page.keyboard.up('ArrowUp');
console.log(JSON.stringify({ info, errors }, null, 2));
await browser.close();
